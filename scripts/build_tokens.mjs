#!/usr/bin/env node
/**
 * Build the design tokens for the web and the app from one source:
 * docs/design/design-tokens.json.
 *
 *   node scripts/build_tokens.mjs                 # write every target present
 *   node scripts/build_tokens.mjs --check         # exit 1 if a target is stale
 *   node scripts/build_tokens.mjs --only web      # web | app | docs
 *
 * Targets (each is skipped when its package is not in this checkout, so the
 * script runs on main, which has no mobile/, and on ios/app, whose portal/
 * predates the token region):
 *   web   portal/public/tokens.css, and the same rules inlined into the
 *         marked region at the top of portal/public/style.css, so a page
 *         needs no second request
 *   app   mobile/src/design/tokens.generated.ts, re-exported by palette.ts
 *         and tokens.ts
 *   docs  the generated tables in docs/design/TOKENS.md
 *
 * The source keeps old names as aliases for one release; see `deprecated` in
 * the JSON. The token tests on both sides run `--check`.
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, relative } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

export const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
export const SOURCE = join(ROOT, 'docs', 'design', 'design-tokens.json')
const TOKENS_CSS = join(ROOT, 'portal', 'public', 'tokens.css')
const STYLE_CSS = join(ROOT, 'portal', 'public', 'style.css')
const APP_TS = join(ROOT, 'mobile', 'src', 'design', 'tokens.generated.ts')
const DOCS = join(ROOT, 'docs', 'design', 'TOKENS.md')

export const STYLE_BEGIN = '/* tokens:begin'
export const STYLE_END = '/* tokens:end */'
const DOCS_BEGIN = '<!-- tokens:begin (generated by scripts/build_tokens.mjs) -->'
const DOCS_END = '<!-- tokens:end -->'

const THEMES = ['light', 'dark', 'lightHighContrast', 'darkHighContrast']
const REF = /^\{([A-Za-z]+)\}$/
const HEX = /^#[0-9A-F]{6}$/

const own = (object) => Object.entries(object).filter(([key]) => !key.startsWith('$'))
const kebab = (name) => name.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`)
const slug = (name) => name.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '')
const rem = (px) => `${+(px / 16).toFixed(4)}rem`
const ratio = (lineHeight, size) => +(lineHeight / size).toFixed(3)
const firstSentence = (text = '') => (text.match(/^.*?\.(?=\s|$)/)?.[0] ?? text).trim()

export function loadSource(file = SOURCE) {
  return JSON.parse(readFileSync(file, 'utf8'))
}

/** Colour roles in source order, with their web and app names. */
export function colourRoles(source) {
  const roles = []
  for (const [group, entries] of own(source.color))
    for (const [name, token] of own(entries)) {
      if (!('$value' in token)) throw new Error(`color.${group}.${name} has no $value`)
      if (!('dark' in token)) throw new Error(`color.${group}.${name} has no dark value`)
      roles.push({
        name,
        group,
        token,
        web: token.web?.name ?? `--${kebab(name)}`,
        app: !token.app?.omit,
        description: token.$description ?? '',
      })
    }
  const names = new Set()
  for (const role of roles) {
    if (names.has(role.name)) throw new Error(`duplicate colour role ${role.name}`)
    names.add(role.name)
  }
  return roles
}

/**
 * Every role's value in each theme. A reference resolves in the theme's base
 * (light or dark): Increase Contrast steps inkFaint to the base inkSoft, not to
 * the stepped-up one. A hex Increase Contrast value needs a dark counterpart.
 */
export function palettes(source) {
  const roles = colourRoles(source)
  const byName = new Map(roles.map((role) => [role.name, role]))
  const raw = {
    light: (role) => role.token.$value,
    dark: (role) => role.token.dark,
    lightHighContrast: (role) => role.token.highContrast,
    darkHighContrast: (role) => {
      const { highContrast, darkHighContrast } = role.token
      if (darkHighContrast !== undefined) return darkHighContrast
      if (highContrast !== undefined && !REF.test(highContrast))
        throw new Error(`${role.name}: a hex highContrast value needs darkHighContrast`)
      return highContrast
    },
  }
  const base = { light: 'light', dark: 'dark', lightHighContrast: 'light', darkHighContrast: 'dark' }
  const resolve = (value, theme, seen = []) => {
    const ref = REF.exec(value)
    if (!ref) return value
    const target = byName.get(ref[1])
    if (!target) throw new Error(`unknown colour reference ${value}`)
    if (seen.includes(ref[1])) throw new Error(`circular reference ${[...seen, ref[1]].join(' > ')}`)
    return resolve(raw[theme](target), theme, [...seen, ref[1]])
  }
  const out = {}
  for (const theme of THEMES) {
    out[theme] = {}
    for (const role of roles) {
      const value = raw[theme](role)
      if (value === undefined) continue
      out[theme][role.name] = resolve(value, base[theme])
    }
  }
  for (const theme of ['light', 'dark'])
    for (const role of roles)
      if (role.app && !HEX.test(out[theme][role.name]))
        throw new Error(`${role.name} (${theme}) must be an opaque #RRGGBB colour: ${out[theme][role.name]}`)
  return out
}

/** Party dots and washes per theme, in source order. */
export function parties(source) {
  const list = own(source.party).map(([key, party]) => ({ key, ...party }))
  for (const party of list)
    for (const value of [party.dot, party.wash, party.dark?.dot, party.dark?.wash])
      if (!HEX.test(value ?? '')) throw new Error(`party.${party.key} needs opaque dot and wash in both themes`)
  return list
}

/** The contrast promises, expanded to one row per pair. */
export function contrastPairs(source) {
  const roles = new Set(colourRoles(source).map((role) => role.name))
  const rows = {}
  for (const [kind, list] of own(source.contrast)) {
    rows[kind] = list.flatMap(({ fg, on }) =>
      on.map((bg) => {
        for (const name of [fg, bg]) if (!roles.has(name)) throw new Error(`contrast.${kind}: unknown role ${name}`)
        return { fg, bg }
      }),
    )
  }
  return rows
}

function typeRole(role, platform) {
  const web = platform === 'web' ? role.web ?? {} : {}
  return {
    family: role.family,
    weight: web.weight ?? role.weight,
    size: web.size ?? role.size,
    lineHeight: web.lineHeight ?? role.lineHeight,
    ramp: role.ramp,
    color: role.color,
    tabular: role.tabular === true,
  }
}

function deprecationNote(entry) {
  const use = entry.alias ?? entry.use
  const change = entry.change && entry.change !== 'none' ? `; moving changes ${entry.change}` : ''
  return `deprecated: use ${use}${change}`
}

/** A TypeScript @deprecated line: names in backticks, the change in brackets. */
function deprecatedDoc(entry) {
  const use = (entry.alias ?? entry.use).replace(/\b(?:rhythm|radii|typeRolesRegular|accents|light)\.\w+|^\w+$|^\w+(?= )/g, (name) => `\`${name}\``)
  const change = entry.change && entry.change !== 'none' ? ` (moving changes ${entry.change})` : ''
  return `@deprecated Use ${use}${change}.`
}

// --- web ---------------------------------------------------------------------

function webDeclarations(source) {
  const roles = colourRoles(source)
  const themes = palettes(source)
  const groups = []
  const push = (title, lines) => groups.push({ title, lines })
  const decl = (name, value, note) => `  ${name}: ${value};${note ? ` /* ${note} */` : ''}`

  for (const group of [...new Set(roles.map((role) => role.group))])
    push(
      `colour: ${group}`,
      roles
        .filter((role) => role.group === group)
        .map((role) =>
          decl(role.web, role.token.web?.value ?? themes.light[role.name], firstSentence(role.description)),
        ),
    )
  const webName = new Map(roles.map((role) => [role.name, role.web]))
  const ref = (name) => `var(${webName.get(name)})`
  push(
    'status tones',
    own(source.status).flatMap(([tone, { ink, wash }]) => [
      decl(`--status-${tone}-ink`, ref(ink)),
      decl(`--status-${tone}-wash`, ref(wash)),
    ]),
  )
  push('chart', [
    ...['mark', 'baseline', 'contrast'].map((key) =>
      decl(`--chart-${key}`, ref(source.chart[key].role), firstSentence(source.chart[key].$description)),
    ),
    ...own(source.chart.industry).flatMap(([cluster, { colour, ink }]) => [
      decl(`--chart-industry-${slug(cluster)}`, colour),
      decl(`--chart-industry-${slug(cluster)}-ink`, ink),
    ]),
  ])
  push(
    'party: a dot beside the name; the wash only on a party header',
    parties(source).flatMap((party) => [
      decl(`--party-${party.web}`, party.dot),
      decl(`--party-${party.web}-wash`, party.wash),
    ]),
  )

  const families = { serif: source.font.serif.web, sans: source.font.sans.web }
  const font = (role) => {
    const size = typeof role.size === 'number' ? rem(role.size) : role.size
    const lineHeight = role.lineHeight > 3 ? ratio(role.lineHeight, role.size) : role.lineHeight
    return `${role.weight} ${size}/${lineHeight} var(--${role.family})`
  }
  push('type: eleven roles; serif speaks for the record, sans for OPAX', [
    decl('--serif', families.serif),
    decl('--sans', families.sans),
    ...own(source.type).map(([name, role]) =>
      decl(`--type-${kebab(name)}`, font(typeRole(role, 'web')), firstSentence(role.$description)),
    ),
  ])
  const space = own(source.space)
  push(
    'space: one rhythm',
    space.map(([name, token]) =>
      decl(`--space-${kebab(name)}`, token.web?.value ?? rem(token.$value), firstSentence(token.$description)),
    ),
  )
  push(
    'radius: press = pill, read = sm, hold = md',
    own(source.radius).map(([name, token]) =>
      decl(`--radius-${kebab(name)}`, typeof token.$value === 'number' ? `${token.$value}px` : token.$value),
    ),
  )
  push(
    'border',
    own(source.border).map(([name, token]) => decl(`--border-${kebab(name)}`, `${token.$value}px`)),
  )
  const shadow = source.elevation.overlay
  const [r, g, b] = [1, 3, 5].map((i) => parseInt(shadow.color.slice(i, i + 2), 16))
  push('elevation: one shadow, for things that float', [
    decl('--shadow-overlay', `${shadow.x} ${shadow.y}px ${shadow.blur}px rgba(${r}, ${g}, ${b}, ${shadow.alpha})`),
  ])
  push('motion: three durations, one curve', [
    ...own(source.motion.duration).map(([name, token]) => decl(`--duration-${kebab(name)}`, `${token.$value}ms`)),
    decl('--ease-standard', `cubic-bezier(${source.motion.easing.standard.$value.join(', ')})`),
    decl('--ambient-loop', `${source.motion.ambientLoop.$value / 1000}s`),
  ])
  push(
    'size',
    own(source.size).map(([name, token]) => {
      const value = token.web ?? token.$value
      return decl(`--size-${kebab(name)}`, typeof value === 'number' ? `${value}px` : value)
    }),
  )
  push('layout', [
    decl('--layout-column-wide', `${source.layout.columnWide.$value}px`),
    decl('--layout-column-web-max', `${source.layout.columnWebMax.$value}px`),
  ])

  const deprecated = own(source.deprecated.web)
  const declared = new Set(groups.flatMap(({ lines }) => lines.map((line) => line.trim().split(':')[0])))
  for (const [name, entry] of deprecated) {
    if (declared.has(name)) throw new Error(`${name} is both a token and a deprecated name`)
    if (entry.alias && !declared.has(entry.alias)) throw new Error(`${name} aliases unknown ${entry.alias}`)
  }
  push(
    'deprecated: kept for one release (docs/design/TOKENS.md)',
    deprecated.map(([name, entry]) => decl(name, entry.alias ? `var(${entry.alias})` : entry.value, deprecationNote(entry))),
  )

  const regular = space
    .filter(([, token]) => token.regular !== undefined && !token.web)
    .map(([name, token]) => decl(`--space-${kebab(name)}`, rem(token.regular)))
  const compact = deprecated.filter(([, entry]) => entry.compact).map(([name, entry]) => decl(name, entry.compact))
  const highContrast = source.themes.web.prefersContrast
    ? roles
        .filter((role) => role.token.highContrast !== undefined && !role.token.web?.value)
        .map((role) => decl(role.web, themes.lightHighContrast[role.name]))
    : []
  return { groups, regular, compact, highContrast }
}

export function buildCss(source) {
  const { groups, regular, compact, highContrast } = webDeclarations(source)
  const blocks = [
    [':root {', `  color-scheme: ${source.themes.web.colorScheme};`, ...groups.flatMap(({ title, lines }) => ['', `  /* ${title} */`, ...lines]), '}'].join('\n'),
  ]
  if (regular.length) blocks.push(`@media (min-width: ${source.layout.regular.$value + 1}px) {\n  :root {\n${regular.map((line) => `  ${line}`).join('\n')}\n  }\n}`)
  if (compact.length) blocks.push(`@media (max-width: ${source.layout.regular.$value}px) {\n  :root {\n${compact.map((line) => `  ${line}`).join('\n')}\n  }\n}`)
  if (highContrast.length) blocks.push(`@media (prefers-contrast: more) {\n  :root {\n${highContrast.map((line) => `  ${line}`).join('\n')}\n  }\n}`)
  return blocks.join('\n') + '\n'
}

export function tokensCss(source) {
  return (
    '/* OPAX design tokens. Generated by scripts/build_tokens.mjs from\n' +
    '   docs/design/design-tokens.json: edit the JSON and run the script, never\n' +
    '   this file. style.css carries the same rules inline. Names, aliases and\n' +
    '   deprecations: docs/design/TOKENS.md. */\n' +
    buildCss(source)
  )
}

/** style.css with its marked token region replaced by the generated rules. */
export function styleWithTokens(style, source) {
  const begin = style.indexOf(STYLE_BEGIN)
  const end = style.indexOf(STYLE_END)
  if (begin < 0 || end < begin) throw new Error('style.css has no tokens:begin / tokens:end region')
  const region =
    `${STYLE_BEGIN}: generated by scripts/build_tokens.mjs from\n` +
    '   docs/design/design-tokens.json, the same rules as tokens.css, inlined so a\n' +
    '   page needs no second request. Edit the JSON, never this region. */\n' +
    buildCss(source)
  return style.slice(0, begin) + region + style.slice(end)
}

