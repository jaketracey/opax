// --- webfonts ---------------------------------------------------------------
// Self-hosting is what removed ~2.3s of render blocking (a serial round trip to
// fonts.googleapis.com just to learn the fonts.gstatic.com URLs) and two origins
// from the CSP. Google still owns the upstream files, so this refreshes them
// from the same CSS2 request using the shared honest agent.
const FONT_CSS_URL =
  'https://fonts.googleapis.com/css2?family=Merriweather:ital,wght@0,400;0,700;0,900;1,400' +
  '&family=Public+Sans:wght@400..700&display=swap'
const FONT_UA = USER_AGENT
// Cyrillic is dropped on purpose: it is ~90 KB of repo for codepoints Hansard
// does not use, and the serif/sans fallbacks cover it if it ever appears.
const KEEP_SUBSETS = new Set(['latin', 'latin-ext', 'vietnamese'])
const FILE_STEM = { Merriweather: 'merriweather', 'Public Sans': 'public-sans' }
// The faces preloaded from index.html: the first serif and the first sans.
const PRELOAD = ['merriweather-normal-latin.woff2', 'public-sans-normal-latin.woff2']

const FONTS_BEGIN = '<!-- fonts:begin (generated by scripts/stamp_assets.mjs --fonts) -->'
const FONTS_END = '<!-- fonts:end -->'

export async function refreshFonts({ publicRoot = PUBLIC, fetcher = honestFetch } = {}) {
  const css = await (await fetcher(FONT_CSS_URL, { headers: { 'user-agent': FONT_UA } })).text()
  const blocks = [...css.matchAll(/\/\*\s*([a-z0-9-]+)\s*\*\/\s*@font-face\s*\{([^}]*)\}/g)]
  if (!blocks.length) pauseSource(FONT_CSS_URL, 'honest CSS does not provide the required WOFF2 subset format; existing fonts kept')

  const dir = join(publicRoot, 'fonts')
  const index = join(publicRoot, 'index.html')
  const faces = []
  const downloads = []
  const seen = new Set()
  for (const [, subset, decl] of blocks) {
    if (!KEEP_SUBSETS.has(subset)) continue
    const family = /font-family:\s*'([^']+)'/.exec(decl)?.[1]
    const style = /font-style:\s*(\w+)/.exec(decl)?.[1]
    const src = /url\((https:\/\/[^)]+)\)/.exec(decl)?.[1]
    const range = /unicode-range:\s*([^;]+);/.exec(decl)?.[1]?.trim().replace(/,\s+/g, ',')
    const weights = /font-weight:\s*(\d+)(?:\s+(\d+))?/.exec(decl)
    if (!FILE_STEM[family] || !style || !src || !range || !weights) pauseSource(FONT_CSS_URL, 'incomplete font declarations; existing fonts kept')
    const requiredMax = family === 'Merriweather' ? 900 : 700
    if (Number(weights[1]) > 400 || Number(weights[2] || weights[1]) < requiredMax) pauseSource(FONT_CSS_URL, 'required font weights unavailable; existing fonts kept')
    const file = `${FILE_STEM[family]}-${style}-${subset}.woff2`
    if (seen.has(file)) continue
    seen.add(file)
    const weight = `400 ${requiredMax}`
    const bytes = Buffer.from(await (await fetcher(src, { headers: { 'user-agent': FONT_UA } })).arrayBuffer())
    if (bytes.subarray(0, 4).toString() !== "wOF2") pauseSource(FONT_CSS_URL, "honest font request did not supply the required format")
    downloads.push([file, bytes])
    faces.push({ family, style, weight, file, range, size: bytes.length })
  }
  const required = [...KEEP_SUBSETS].flatMap(subset => [
    `merriweather-normal-${subset}.woff2`, `merriweather-italic-${subset}.woff2`,
    `public-sans-normal-${subset}.woff2`,
  ])
  for (const want of required) {
    if (!seen.has(want)) pauseSource(FONT_CSS_URL, `required face ${want} unavailable; existing fonts kept`)
  }

  const block = [
    FONTS_BEGIN,
    ...PRELOAD.map(
      (f) => `<link rel="preload" as="font" type="font/woff2" crossorigin href="/fonts/${f}">`,
    ),
    '<style>',
    ...faces.map(
      ({ family, style, weight, file, range }) =>
        `@font-face{font-family:'${family}';font-style:${style};font-weight:${weight};` +
        `font-display:swap;src:url(/fonts/${file}) format('woff2');unicode-range:${range}}`,
    ),
    '</style>',
    FONTS_END,
  ].join('\n')

  const html = readFileSync(index, 'utf8')
  const start = html.indexOf(FONTS_BEGIN)
  const end = html.indexOf(FONTS_END)
  if (start < 0 || end < 0) throw new Error('fonts:begin/fonts:end markers missing from index.html')
  // All required faces, bytes and page markers are validated before publication.
  mkdirSync(dir, { recursive: true })
  for (const [file, bytes] of downloads) writeFileSync(join(dir, file), bytes)
  for (const stale of readdirSync(dir)) {
    if (stale.endsWith('.woff2') && !seen.has(stale)) unlinkSync(join(dir, stale))
  }
  writeFileSync(index, html.slice(0, start) + block + html.slice(end + FONTS_END.length))
  for (const f of faces) console.log(`  font  ${f.file.padEnd(38)} ${String(f.size).padStart(7)} bytes`)
}

