#!/usr/bin/env node
/**
 * The loading animals' walk, sampled into CSS keyframes for
 * portal/public/loader.css (the region between gait:begin and gait:end).
 *
 *   node scripts/build_loader_gait.mjs           # rewrite the region
 *   node scripts/build_loader_gait.mjs --check   # exit 1 if it is stale
 *
 * One 20s loop (the 16s --ambient-loop, times 1.25): walk on, slow to a stop
 * at the middle of the stage, stand for one beat, start again and walk off.
 * The stage move and the legs are worked out together here, so a foot on the
 * ground stays put while the body passes over it:
 *
 *   - wb-trundle moves the animal along the stage: steady, then a quadratic
 *     ease out into the stop and in out of it;
 *   - wb-stride eases --wb-amp from 1 to 0 over the same 0.6s, and every
 *     moving part multiplies its swing by it, so the steps shorten as the
 *     walk slows and the legs settle into the drawn standing pose;
 *   - the gait keyframes run on their own short period underneath (one
 *     stride, both legs), so nothing has to line up with the stop.
 *
 * The emu's legs are two-bone: a thigh from the hip to the backward-bending
 * joint, a shin to the heel and the toes flat on the ground. Each sample
 * places the heel (planted through the stance, lifted on a sine through the
 * swing) and solves the two angles; the toes counter-rotate to stay flat,
 * and droop while the foot is in the air. The keyframes hold the angles as
 * offsets from the drawn pose in wombat.js, which uses EMU.hip, EMU.knee
 * and EMU.heel below; keep the two in step.
 *
 * The three short-legged animals share one normalised shuffle (each leg's
 * swing, lift and the body's bob and roll in -1..1), scaled per animal in
 * loader.css. --wb-* are registered (@property) numbers, so they animate
 * smoothly and the transforms in loader.css read them through calc().
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
export const LOADER_CSS = join(ROOT, 'portal', 'public', 'loader.css')
export const BEGIN = '/* gait:begin (generated by scripts/build_loader_gait.mjs; edit the script, not this region) */'
export const END = '/* gait:end */'

// --- the loop ----------------------------------------------------------------
export const LOOP = 20 // s; loader.css: calc(var(--ambient-loop) * 1.25)
const PAUSE = [44, 56] // % of the loop standing still
const EASE = 3 // % either side of the pause spent slowing down and starting up
// Along the 320px stage (the 65px walker box's left edge): enter with the
// beak just out of view, stop at the middle, leave with the tail just out.
const ENTER = -50
const CENTRE = (320 - 65) / 2
const UNIT = 65 / 120 // px per viewBox unit
const walking = (LOOP * (PAUSE[0] - EASE)) / 100 // s at full speed each way
const easing = (LOOP * EASE) / 100 // s to stop, and to start
export const SPEED = (CENTRE - ENTER) / (walking + easing / 2) // px/s; a quadratic stop covers half its time at speed
const LEAVE = CENTRE + (CENTRE - ENTER)

// --- the emu -----------------------------------------------------------------
export const EMU = {
  period: 0.8, // s per stride: two steps
  duty: 0.6, // share of the stride each foot is on the ground
  hip: [47, 45.5],
  ground: 68, // heel and toes, stroke centre
  thigh: 12,
  shin: 12.5,
  reach: 0.5, // the standing heel sits this far ahead of the hip
  lift: 4.6, // heel height at mid-swing
  droop: 32, // degrees the toes hang at mid-swing
  bob: 0.9, // body drop after each heel strike, rise over the standing leg
  nod: 1, // the neck's nod, scaled by --wb-nod-deg in loader.css
  lag: 0.07, // of a stride: the head trails the body
}
EMU.stride = ((SPEED / UNIT) * EMU.duty * EMU.period) // viewBox units the planted foot travels

const SAMPLES = 20
const DEG = 180 / Math.PI
const round = (n) => {
  const v = Math.round(n * 100) / 100
  return Object.is(v, -0) ? 0 : v
}
const pct = (i) => `${round((i / SAMPLES) * 100)}%`

/** Body drop (+) or rise (-) at stride phase p: lowest just after each heel strike. */
const bobAt = (p) => EMU.bob * Math.cos(4 * Math.PI * (p - (1 - EMU.duty) / 4))

function solve([hx, hy], [fx, fy]) {
  const reach = (EMU.thigh + EMU.shin) * 0.995
  let dx = fx - hx
  let dy = fy - hy
  let d = Math.hypot(dx, dy)
  if (d > reach) { dx *= reach / d; dy *= reach / d; d = reach }
  const along = Math.atan2(dy, dx)
  const bend = Math.acos((EMU.thigh ** 2 + d ** 2 - EMU.shin ** 2) / (2 * EMU.thigh * d))
  const upper = along + bend // + bends the joint backwards (to -x), as a bird's does
  const knee = [hx + EMU.thigh * Math.cos(upper), hy + EMU.thigh * Math.sin(upper)]
  const lower = Math.atan2(hy + dy - knee[1], hx + dx - knee[0])
  return { upper, lower, knee, heel: [hx + dx, hy + dy] }
}

const rest = solve(EMU.hip, [EMU.hip[0] + EMU.reach, EMU.ground])
EMU.knee = rest.knee.map(round)
EMU.heel = rest.heel.map(round)

/** One leg at stride phase p (0 = heel strike): offsets from the drawn pose, in degrees. */
export function emuLeg(p) {
  const s = EMU.stride
  let x, lift = 0, toe = 0
  if (p < EMU.duty) {
    x = EMU.reach + s / 2 - (s * p) / EMU.duty
  } else {
    const u = (p - EMU.duty) / (1 - EMU.duty)
    x = EMU.reach - s / 2 + (s * (1 - Math.cos(Math.PI * u))) / 2
    lift = EMU.lift * Math.sin(Math.PI * u)
    toe = EMU.droop * Math.sin(Math.PI * u)
  }
  // In the body's frame the ground moves by the bob.
  const pose = solve(EMU.hip, [EMU.hip[0] + x, EMU.ground - bobAt(p) - lift])
  const hip = (pose.upper - rest.upper) * DEG
  const shin = (pose.lower - rest.lower) * DEG
  return { hip, knee: shin - hip, toe: toe - shin, heel: pose.heel }
}

// --- the short-legged three ----------------------------------------------------
export const QUAD = { period: 0.72, duty: 0.5 }

function quadLeg(p) {
  if (p < QUAD.duty) return { swing: -1 + (2 * p) / QUAD.duty, lift: 0 }
  const u = (p - QUAD.duty) / (1 - QUAD.duty)
  return { swing: 1 - (1 - Math.cos(Math.PI * u)), lift: Math.sin(Math.PI * u) }
}

// --- css ---------------------------------------------------------------------
const frames = (name, row) => {
  const rows = []
  for (let i = 0; i <= SAMPLES; i++) rows.push(`  ${pct(i).padEnd(4)} { ${row(i / SAMPLES)} }`)
  return `@keyframes ${name} {\n${rows.join('\n')}\n}`
}

export function gaitCss() {
  const out = (n) => `${round(n)}px`
  const x1 = CENTRE - SPEED * (easing / 2)
  const x2 = CENTRE + SPEED * (easing / 2)
  const ezOut = 'cubic-bezier(0.333, 0.667, 0.667, 1)'
  const ezIn = 'cubic-bezier(0.333, 0, 0.667, 0.333)'
  const [stop, go] = PAUSE
  const blocks = [
    `/* ${round(SPEED)}px/s on the stage; the emu's planted foot covers ${round(EMU.stride)} units a step. */`,
    `@keyframes wb-trundle {
  0%   { transform: translateX(${out(ENTER)}); animation-timing-function: linear; }
  ${stop - EASE}%  { transform: translateX(${out(x1)}); animation-timing-function: ${ezOut}; }
  ${stop}%  { transform: translateX(${out(CENTRE)}); animation-timing-function: linear; }
  ${go}%  { transform: translateX(${out(CENTRE)}); animation-timing-function: ${ezIn}; }
  ${go + EASE}%  { transform: translateX(${out(x2)}); animation-timing-function: linear; }
  100% { transform: translateX(${out(LEAVE)}); }
}`,
    `@keyframes wb-stride {
  0%, ${stop - EASE}% { --wb-amp: 1; }
  ${stop}%, ${go}% { --wb-amp: 0; }
  ${go + EASE}%, 100% { --wb-amp: 1; }
}`,
    `.wb-a-emu .wb-thigh { transform-origin: ${EMU.hip.map(out).join(' ')}; }
.wb-a-emu .wb-shin  { transform-origin: ${EMU.knee.map(out).join(' ')}; }
.wb-a-emu .wb-toes  { transform-origin: ${EMU.heel.map(out).join(' ')}; }`,
    frames('wb-emu-leg', (p) => {
      const l = emuLeg(p % 1)
      return `--wb-hip: ${round(l.hip)}; --wb-knee: ${round(l.knee)}; --wb-toe: ${round(l.toe)};`
    }),
    frames('wb-emu-body', (p) =>
      `--wb-bob: ${round(bobAt(p))}; --wb-nod: ${round(EMU.nod * Math.cos(4 * Math.PI * (p - (1 - EMU.duty) / 4 - EMU.lag)))};`),
    frames('wb-quad-leg', (p) => {
      const l = quadLeg(p % 1)
      return `--wb-hip: ${round(l.swing)}; --wb-lift: ${round(l.lift)};`
    }),
    frames('wb-quad-body', (p) =>
      `--wb-bob: ${round(-Math.abs(Math.sin(2 * Math.PI * p)))}; --wb-rock: ${round(Math.sin(2 * Math.PI * p))};`),
  ]
  return `${BEGIN}\n${blocks.join('\n')}\n${END}`
}

export function staleLoaderCss(file = LOADER_CSS) {
  const css = readFileSync(file, 'utf8')
  const a = css.indexOf(BEGIN)
  const b = css.indexOf(END)
  if (a < 0 || b < a) throw new Error(`${file} has no gait:begin / gait:end region`)
  const next = css.slice(0, a) + gaitCss() + css.slice(b + END.length)
  return next === css ? null : next
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  const next = staleLoaderCss()
  if (process.argv.includes('--check')) {
    if (next) { console.error('loader.css: the gait region is stale; run `node scripts/build_loader_gait.mjs`.'); process.exit(1) }
    console.log('loader.css: the gait region is current.')
  } else if (next) {
    writeFileSync(LOADER_CSS, next)
    console.log(`loader.css: gait region written (emu knee ${EMU.knee.join(',')}, heel ${EMU.heel.join(',')}).`)
  } else {
    console.log('loader.css: the gait region is current.')
  }
}
