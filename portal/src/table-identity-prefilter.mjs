import {createHash} from 'node:crypto';
import {identityWords,legacyIdentityWords,identityStrippedWords,STRIPPED_PREFIX,STRIPPED_MIN_LENGTH,STRIPPED_CONTAINS_MIN_LENGTH,ROW_IDENTITY_POLICY} from './table-identities.mjs';

// Polynomial hashes over UTF-16 code units, modulo 2^32. Both the rolling
// calculation and build-time calculation include the stripped domain prefix.
const BASE=31;
export function identityQuickHash(text) {
  let hash=0;
  for(let i=0;i<text.length;i++)hash=(Math.imul(hash,BASE)+text.charCodeAt(i))>>>0;
  return hash;
}

// Source text stays in build memory. The numeric index stays server-side and is
// deliberately excluded from the identity-only privacy fingerprint.
const digest=value=>createHash('sha256').update(value).digest('hex');
export function identityRegistryFingerprint(entries) {
  const sorted=[...entries].sort((a,b)=>a.hash.localeCompare(b.hash));
  return entries.every(e=>Object.hasOwn(e,'row'))
    ? digest(ROW_IDENTITY_POLICY+'\n'+sorted.map(e=>e.hash+':'+e.row).join('\n'))
    : digest(sorted.map(e=>e.hash).join('\n'));
}
const unavailable=()=>{throw Error('Privacy index unavailable');};
/** Verify the complete SHA registry while source forms are still in memory.
 * Counts include quick-hash collisions: every SHA has a domain/length entry. */
export function buildIdentityPrefilter(phrases,entries,registryFingerprint) {
  const registry=new Map(entries.map(entry=>[entry.hash,entry.words]));
  if(!entries.length || registry.size!==entries.length || identityRegistryFingerprint(entries)!==registryFingerprint)unavailable();
  const forms=new Set(phrases),words={},stripped={},counts={words:{},stripped:{}},seen=new Set();
  for(const phrase of forms) {
    const sha=digest(phrase);
    if(!registry.has(sha) || registry.get(sha)!==phrase.split(' ').length || seen.has(sha))unavailable();
    seen.add(sha);
    const compact=phrase.startsWith(STRIPPED_PREFIX),groups=compact ? stripped : words;
    const size=compact ? phrase.length-STRIPPED_PREFIX.length : phrase.split(' ').length;
    (groups[size] ||= new Set()).add(identityQuickHash(phrase));
    const domain=compact ? counts.stripped : counts.words;
    domain[size]=(domain[size] || 0)+1;
  }
  if(seen.size!==registry.size)unavailable();
  const serialise=groups=>Object.fromEntries(Object.entries(groups).map(([size,hashes])=>[size,[...hashes].sort((a,b)=>a-b)]));
  const data={version:2,registryFingerprint,identityFingerprint:digest([...registry.keys()].sort().join('\n')),words:serialise(words),stripped:serialise(stripped),counts,registryCount:registry.size,
    lengths:[...new Set(entries.map(e=>e.words))].sort((a,b)=>a-b),strippedLengths:Object.keys(stripped).map(Number).sort((a,b)=>a-b)};
  // Recheck each SHA's bucket before sealing; never trust totals alone.
  for(const phrase of forms) {
    const compact=phrase.startsWith(STRIPPED_PREFIX),size=compact ? phrase.length-STRIPPED_PREFIX.length : phrase.split(' ').length;
    if(!(compact ? data.stripped : data.words)[size]?.includes(identityQuickHash(phrase)))unavailable();
  }
  return {...data,checksum:digest(JSON.stringify(data))};
}
/** This binding is emitted separately in the private generated module. Runtime
 * callers use that trusted binding, never a checksum supplied by an asset. */
export function identityPrefilterBinding(prefilter) {
  return {version:2,registryFingerprint:prefilter.registryFingerprint,checksum:prefilter.checksum};
}
export function verifyIdentityPrefilter(prefilter,phrases,entries,registryFingerprint) {
  const expected=buildIdentityPrefilter(phrases,entries,registryFingerprint);
  if(JSON.stringify(prefilter)!==JSON.stringify(expected))unavailable();
}
export function identityPrefilterModule(prefilter,phrases,entries,registryFingerprint) {
  verifyIdentityPrefilter(prefilter,phrases,entries,registryFingerprint);
  return '// Generated by scripts/load_tables.mjs. Server only; never copy to public/.\n'+
    'export const prefilter='+JSON.stringify(prefilter)+';\n'+
    'export const binding=Object.freeze('+JSON.stringify(identityPrefilterBinding(prefilter))+');\n'+
    'export const identityHashes='+JSON.stringify(entries.map(e=>e.hash).sort())+';\n';
}
export function assertPrefilterLengths(prefilter,lengths,compactLengths) {
  const equal=(a,b)=>Array.isArray(a) && a.length===b.length && [...a].sort((x,y)=>x-y).every((n,i)=>Number.isSafeInteger(n) && n===b[i]);
  if(!equal(lengths,prefilter.lengths) || !equal(compactLengths,prefilter.strippedLengths))unavailable();
}

// Sparse typed arrays are faster than a Set lookup at every substring. Zero is
// an empty slot; a zero quick hash always reaches SHA-256 confirmation instead.
function hashTable(hashes) {
  let size=4;while(size<hashes.length*4)size*=2;
  const slots=new Uint32Array(size),mask=size-1;
  for(const hash of hashes) {
    if(!hash)continue;
    let at=(hash^(hash>>>16))&mask;while(slots[at] && slots[at]!==hash)at=(at+1)&mask;
    slots[at]=hash;
  }
  return {slots,mask};
}
function contains(table,hash) {
  if(!table || !hash)return true;
  let at=(hash^(hash>>>16))&table.mask,current;
  while((current=table.slots[at])) {if(current===hash)return true;at=(at+1)&table.mask;}
  return false;
}
function compileGroups(groups,min) {
  if(!groups || typeof groups!=='object' || Array.isArray(groups))throw Error('Invalid prefilter');
  return new Map(Object.entries(groups).map(([size,hashes])=>{
    if(!/^[1-9]\d*$/.test(size) || !Number.isSafeInteger(Number(size)) || Number(size)<min || !Array.isArray(hashes) || !hashes.length || hashes.some(h=>!Number.isInteger(h)||h<0||h>0xffffffff))throw Error('Invalid prefilter');
    return [Number(size),hashTable(hashes)];
  }));
}
function rolling(text) {
  const hashes=new Uint32Array(text.length+1),powers=new Uint32Array(text.length+1);powers[0]=1;
  for(let i=0;i<text.length;i++) {
    hashes[i+1]=(Math.imul(hashes[i],BASE)+text.charCodeAt(i))>>>0;
    powers[i+1]=Math.imul(powers[i],BASE)>>>0;
  }
  return {hashes,powers};
}
// Keep the hot window scan in a regular function: generators suspend only for
// the handful of prefilter hits, never for the thousands of rejected windows.
function compactHits(tokens,lengths,groups) {
  const compact=tokens.join(''),{hashes,powers}=rolling(compact),hits=[];
  const starts=new Uint8Array(compact.length+1),ends=new Uint8Array(compact.length+1);
  let at=0;for(const token of tokens){starts[at]=1;at+=token.length;ends[at]=1;}
  const prefixHash=identityQuickHash(STRIPPED_PREFIX);
  for(const size of lengths) {
    if(!Number.isSafeInteger(size) || size<STRIPPED_MIN_LENGTH || size>compact.length)continue;
    const table=groups.get(size),power=powers[size],domain=Math.imul(prefixHash,power);
    const slots=table?.slots,mask=table?.mask,short=size<STRIPPED_CONTAINS_MIN_LENGTH;
    for(let start=0,end=size;end<=compact.length;start++,end++) {
      if(short && (!starts[start] || !ends[end]))continue;
      const hash=(domain+hashes[end]-Math.imul(hashes[start],power))>>>0;
      if(slots && hash) {
        let at=(hash^(hash>>>16))&mask,current;
        while((current=slots[at]) && current!==hash)at=(at+1)&mask;
        if(!current)continue;
      }
      hits.push(STRIPPED_PREFIX+compact.slice(start,end));
    }
  }
  return hits;
}

/** SHA-256 makes the final decision. Candidate skipping requires the complete
 * build artifact's trusted binding; any invalid artifact fails closed. */
export function compileIdentityPrefilter(prefilter,registryFingerprint,binding) {
  let wordGroups,compactGroups;
  try {
    if(prefilter?.version!==2 || binding?.version!==2 || !/^[a-f0-9]{64}$/.test(registryFingerprint) || prefilter.registryFingerprint!==registryFingerprint || binding.registryFingerprint!==registryFingerprint)unavailable();
    const {checksum,...data}=prefilter;
    if(!/^[a-f0-9]{64}$/.test(binding.checksum) || checksum!==binding.checksum || checksum!==digest(JSON.stringify(data)))unavailable();
    wordGroups=compileGroups(prefilter.words,1);compactGroups=compileGroups(prefilter.stripped,STRIPPED_MIN_LENGTH);
    let total=0;
    for(const domain of ['words','stripped']) {
      if(!prefilter.counts?.[domain] || Object.keys(prefilter.counts[domain]).length!==Object.keys(prefilter[domain]).length)unavailable();
      for(const [size,hashes] of Object.entries(prefilter[domain])) {
        const count=prefilter.counts[domain][size];
        if(!Number.isSafeInteger(count) || count<hashes.length || new Set(hashes).size!==hashes.length)unavailable();
        total+=count;
      }
    }
    if(total!==prefilter.registryCount || !total)unavailable();
    assertPrefilterLengths(prefilter,[...new Set([...wordGroups.keys(),...(compactGroups.size ? [1] : [])])],[...compactGroups.keys()]);
  } catch {unavailable();}
  return function* (value,lengths,compactLengths=[]) {
    // Preserve all three coercions even when a lazy matcher stops at a word hit.
    const words=identityWords(value),legacy=legacyIdentityWords(value),compactTokens=identityStrippedWords(value),seen=new Set();
    for(const tokens of [words,legacy]) {
      // These normalisations often coincide: visit that word domain only once.
      if(tokens===legacy && words.length===legacy.length && words.every((word,i)=>word===legacy[i]))continue;
      const text=tokens.join(' '),{hashes,powers}=rolling(text),starts=[],ends=[];
      let at=0;for(const token of tokens){starts.push(at);at+=token.length;ends.push(at);at++;}
      for(const size of lengths) {
        const table=wordGroups.get(size);
        for(let i=0;i+size<=tokens.length;i++) {
          const start=starts[i],end=ends[i+size-1];
          const hash=(hashes[end]-Math.imul(hashes[start],powers[end-start]))>>>0;
          if(!contains(table,hash))continue;
          const candidate=text.slice(start,end);
          if(!seen.has(candidate)){seen.add(candidate);yield candidate;}
        }
      }
    }
    // ABNs use the accent-insensitive tokens, exactly as the original matcher.
    const digitTable=wordGroups.get(1);
    for(let i=0;i<words.length;i++) {
      let digits='';
      for(let j=i;j<words.length && /^\d+$/.test(words[j]) && digits.length<11;j++) {
        digits+=words[j];
        if(digits.length===11 && contains(digitTable,identityQuickHash(digits)) && !seen.has(digits)){seen.add(digits);yield digits;}
      }
    }
    for(const candidate of compactHits(compactTokens,compactLengths,compactGroups))if(!seen.has(candidate)){seen.add(candidate);yield candidate;}
  };
}
