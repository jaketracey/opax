test('dot segments and encoded slashes never reach another route, literal or encoded', () => {
  for (const bad of [
    '/doc/..', '/doc/.', '/doc/a/..', '/doc/../community', '/doc/../api/community/status', '/doc/../../../../community',
    '/subject/person/../../community', '/doc/%2e%2e/community', '/doc/%2E%2E', '/doc/.%2e', '/doc/%2F..%2Fcommunity',
    '/doc/%2Fcommunity', '/subject/campaigner/T%2FA%20Union', '/doc/．．/community',
  ]) assert.equal(supportRecord(bad), '', bad);
  // The reviewer's forms through the outer query: once encoded, and twice.
  for (const query of ['record=%2Fdoc%2F..%2Fcommunity', 'record=%2Fdoc%2F%252e%252e%2Fcommunity', 'record=%252Fdoc%252F..%252Fcommunity']) {
    assert.equal(supportRecord(received(query)), '', query);
  }
});

test('OPAX tokens never pass, in any record position', () => {
  // The reviewer's synthetic, inactive token: digitless, so the old rule let it through.
  const synthetic = 'AbCdEfGhIj-KlMnOpQrSt-UvWxYzAbCd-EfGhIjKlMk';
  assert.equal(supportRecord(received('record=%2Fdoc%2FAbCdEfGhIj-KlMnOpQrSt-UvWxYzAbCd-EfGhIjKlMk')), '');
  const positions = (t) => [
    `/doc/${t}`, `/bill/${t}`, `/reports/${t}`, `/subject/topic/${t}`,
    ...['person', 'party', 'donor', 'supplier', 'agency', 'campaigner', 'electorate'].map((dir) => `/subject/${dir}/${t}`),
    `/money/grants/federal/recipient/name:${t}`, `/money/grants/qld/recipient/person:${t}`, `/doc/opax_${t}`,
  ];
  for (const path of positions(synthetic)) assert.equal(supportRecord(path), '', path);
  let tried = 0;
  const accepted = [];
  for (let i = 0; i < 10_000; i++) {
    const token = randomToken();
    assert.equal(token.length, 43);
    for (const path of positions(token)) {
      tried++;
      if (supportRecord(path) || supportRecord(received(`record=${encodeURIComponent(path)}`))) accepted.push(path);
    }
  }
  assert.deepEqual(accepted, [], `${accepted.length} of ${tried} token paths accepted`);
});

test('the GitHub issue is pre-filled with the record, or left general without one', () => {
  const withRecord = new URL(supportIssueUrl('/subject/person/Tony Abbott'));
  assert.equal(withRecord.origin + withRecord.pathname, 'https://github.com/jaketracey/opax/issues/new');
  assert.equal(withRecord.searchParams.get('title'), 'Correction: /subject/person/Tony Abbott');
  assert.match(withRecord.searchParams.get('body'), /^Record: https:\/\/opax\.com\.au\/subject\/person\/Tony%20Abbott\n\nWhat is wrong:/);
  for (const raw of ['/doc/abc?email=person%40example.invalid&token=synthetic-token#note', '/community?token=synthetic-token',
    '/doc/AbCdEfGhIj-KlMnOpQrSt-UvWxYzAbCd-EfGhIjKlMk', '/doc/../community']) {
    const url = supportIssueUrl(supportRecord(raw));
    assert.doesNotMatch(decodeURIComponent(url), /example\.invalid|synthetic-token|note|AbCdEf|community/, raw);
  }
  const general = new URL(supportIssueUrl(''));
  assert.equal(general.searchParams.get('title'), 'Correction');
  assert.match(general.searchParams.get('body'), /^Record or page:/);
});

test('every record path in the search catalog is kept, or the refusals are counted', (t) => {
  // The catalog is build output (npm run build:search); the deploy workflow builds it before tests.
  const root = new URL('../public/search-catalog/', import.meta.url);
  const versions = existsSync(root) ? readdirSync(root, { withFileTypes: true }).filter((d) => d.isDirectory()) : [];
  if (!versions.length) { t.skip('no search catalog built'); return; }
  const paths = new Set();
  for (const dir of versions) {
    for (const file of readdirSync(new URL(`${dir.name}/`, root)).filter((f) => f.startsWith('records-'))) {
      const text = readFileSync(new URL(`${dir.name}/${file}`, root), 'utf8');
      for (const m of text.matchAll(/"(\/(?:doc|bill|bills|reports|subject|money|connections|declared|discover|explore)(?:\/[^"?#\s]*)?)"/g)) paths.add(m[1]);
    }
  }
  const refused = [...paths].filter((p) => !supportRecord(p));
  t.diagnostic(`${refused.length} of ${paths.size} catalog record paths refused: ${refused.slice(0, 5).join(' | ')}`);
  // Names holding an encoded slash ("T%2FA") are refused by rule; nothing else should be.
  assert.deepEqual(refused.filter((p) => !/%2F/i.test(p)), []);
});

test('/support is a shell route with metadata and a sitemap entry', () => {
  const html = readFileSync(new URL('../public/index.html', import.meta.url), 'utf8');
  const worker = readFileSync(new URL('../src/index.ts', import.meta.url), 'utf8');
  assert.match(html, /<section id="panel-support" class="panel" hidden/);
  assert.match(app, /const PANELS = \[[^\]]*"support"/);
  assert.match(worker, /support: \{\n\s+title: 'Support · OPAX'/);
  assert.match(worker, /'privacy', 'support'\]\) add\(`\/\$\{page\}`\)/);
  for (const page of ['index.html', 'home.html', 'community.html']) {
    assert.match(readFileSync(new URL(`../public/${page}`, import.meta.url), 'utf8'), /href="\/support"/, page);
  }
});
