import { test } from 'node:test';
import assert from 'node:assert/strict';
import { existsSync, readFileSync, readdirSync } from 'node:fs';
import { runInNewContext } from 'node:vm';

// /support?record=<path> names the record a report is about and pre-fills the
// public GitHub issue. Only a public record route's own shape may reach either.
const app = readFileSync(new URL('../public/app.js', import.meta.url), 'utf8');
const pick = (name) => app.match(new RegExp(`function ${name}\\([^)]*\\) \\{[\\s\\S]*?\\n\\}`))[0];
const constant = (name) => app.match(new RegExp(`^const ${name} = .*$`, 'm'))[0];
const { supportRecord, supportRecordHref, supportIssueUrl } = runInNewContext(
  `const SITE_ORIGIN = "https://opax.com.au"; ${constant('SUPPORT_ISSUES')} ${constant('SUPPORT_DIRS')} ${constant('SUPPORT_SECTIONS')}
   ${pick('supportRecord')} ${pick('supportRecordHref')} ${pick('supportIssueUrl')} ({ supportRecord, supportRecordHref, supportIssueUrl })`,
  { URLSearchParams, String, encodeURIComponent, decodeURIComponent },
);
// The record value as /support receives it: the outer query decoded once, as renderSupport does.
const received = (query) => new URLSearchParams(query).get('record');

// OPAX's own sign-in, session and deletion tokens (src/community-core.ts),
// generated by the real function: 32 random bytes as base64url, 43 characters.
const core = readFileSync(new URL('../src/community-core.ts', import.meta.url), 'utf8');
const randomToken = runInNewContext(`(${core.match(/export const randomToken = (\(\) => \{[^\n]*\})/)[1]})`, { crypto, btoa, Uint8Array, String });

