#!/usr/bin/env node
// Mobile's final token surface. The shared generator still supports the web's
// transition release; this target omits those aliases without changing the web.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { format } from 'prettier';
import { buildTs, loadSource } from '../../scripts/build_tokens.mjs';

export async function mobileTokens() {
  const source = loadSource();
  for (const key of [
    'roles',
    'textStyles',
    'typeRolesRegular',
    'accents',
    'spacing',
  ])
    source.deprecated.app[key] = {};
  for (const [key, value] of Object.entries(source.radius))
    if (value.alias) delete source.radius[key];
  source.color.photo = {
    photoGround: {
      $value: '#000000',
      dark: '#000000',
      $description: 'Photograph viewer ground.',
    },
    photoScrim: {
      $value: '#000000',
      dark: '#000000',
      $description: 'Photograph caption scrim.',
    },
    photoScrimStrong: {
      $value: '#000000',
      dark: '#000000',
      $description: 'Photograph caption scrim at increased contrast.',
    },
    photoBarScrim: {
      $value: '#000000',
      dark: '#000000',
      $description: 'Photograph viewer bar scrim.',
    },
  };
  // App-only roles that carry alpha (`appOnly` in the token source): the
  // shared generator holds opaque hex only, so each goes in as a placeholder
  // and takes its real value per theme below.
  const alphaRoles = Object.entries(source.appOnly ?? {}).filter(
    ([key]) => !key.startsWith('$'),
  );
  const PLACEHOLDER = '#000000';
  source.color.appOnly = Object.fromEntries(
    alphaRoles.map(([name, token]) => {
      if (token.$value === undefined || token.dark === undefined)
        throw new Error(`appOnly.${name} needs a light and a dark value`);
      if (
        (token.highContrast === undefined) !==
        (token.darkHighContrast === undefined)
      )
        throw new Error(
          `appOnly.${name}: give both Increase Contrast values or neither`,
        );
      return [
        name,
        {
          $value: PLACEHOLDER,
          dark: PLACEHOLDER,
          ...(token.highContrast === undefined
            ? {}
            : { highContrast: PLACEHOLDER, darkHighContrast: PLACEHOLDER }),
          $description: token.$description,
        },
      ];
    }),
  );
  let output = buildTs(source).replace(
    /\/\*\* @deprecated The web's old phone scale: use `rhythm`\. \*\/\nexport const spacing = \{\} as const;\n/,
    '',
  );
  for (const [role, alpha] of Object.entries({
    photoScrim: 0.7,
    photoScrimStrong: 0.85,
    photoBarScrim: 0.4,
  }))
    output = output.replaceAll(
      `${role}: '#000000'`,
      `${role}: 'rgba(0,0,0,${alpha})'`,
    );
  for (const [name, token] of alphaRoles)
    for (const [theme, value] of [
      ['light', token.$value],
      ['dark', token.dark],
      ['lightHighContrast', token.highContrast],
      ['darkHighContrast', token.darkHighContrast],
    ]) {
      if (value === undefined) continue;
      const start = output.indexOf(`export const ${theme}`);
      const end = output.indexOf('\n}', start);
      const entry = `  ${name}: '${PLACEHOLDER}',`;
      const at = output.indexOf(entry, start);
      if (start < 0 || at < 0 || at > end)
        throw new Error(`appOnly.${name} is missing from ${theme}`);
      output =
        output.slice(0, at) +
        `  ${name}: '${value}',` +
        output.slice(at + entry.length);
    }
  output = output.replace(
    /\/\/ OPAX design tokens\.[\s\S]*?(?=\/\*\* Colour roles)/,
    '// OPAX mobile tokens. Generated by scripts/build-design-tokens.mjs.\n// Shared values come from docs/design/design-tokens.json; mobile omits retired aliases.\n\n',
  );
  return format(output, { parser: 'typescript', singleQuote: true });
}
const target = fileURLToPath(
  new URL('../src/design/tokens.generated.ts', import.meta.url),
);
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const output = await mobileTokens();
  if (process.argv.includes('--check')) {
    if (readFileSync(target, 'utf8') !== output)
      throw new Error('Mobile design tokens are stale: run npm run tokens');
  } else writeFileSync(target, output);
}
